export function is_prime(n) {
  // Числа меньше или равные 1 не являются простыми
  if (n <= 1) return false;

  let d = 2;
  // Проверяем делители от 2 до квадратного корня из n
  while (d * d <= n) {
    if (n % d === 0) {
      return false; // Нашли делитель (число не простое)
    }
    d++;
  }
  return true; // Делителей нет (число простое)
}

